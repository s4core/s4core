//! The secrets of S3 credentials, encrypted in the user's record.
//!
//! AWS Signature V4 is an HMAC keyed by the secret itself, so the server has
//! to hold the secret, not only its hash. It is held encrypted: AES-256-GCM,
//! with the user's id and access key as associated data, so a sealed secret
//! copied into another user's record does not open (plan
//! CLUSTER-IAM-REPLICATION.md, decision 7). A record names the key it was
//! sealed with by a [`SecretKey::id`], an HMAC of the key that tells nothing
//! about it.
//!
//! Where the key comes from, in this order:
//!
//! 1. `S4_IAM_ENCRYPTION_KEY` — 32 bytes in hex, the same on every node;
//! 2. derived by HKDF-SHA256 from a configured `S4_JWT_SECRET` (label
//!    `s4-iam-secret-v1`), so an upgrade needs no new variable;
//! 3. a key a node generated for itself and keeps in its own storage
//!    (`__s4_iam_node_secret_key`, never replicated): a single node without
//!    either, whose JWT secret is random at every start. The secrets are then
//!    not readable from the volumes alone, but whoever reads the whole data
//!    directory can open them.
//!
//! Besides the current key, a node opens records sealed with
//! `S4_IAM_ENCRYPTION_KEY_PREVIOUS`, with the key derived from the JWT secret
//! when a configured key replaced it, and with its own generated key when it
//! has one. Records sealed with any of them — or kept in clear text by an
//! earlier release — are sealed again with the current key by a pass under
//! the lease of IAM changes ([`super::IamStorage::reseal_secrets`]).

use std::collections::BTreeMap;
use std::sync::Arc;

use aes_gcm::aead::{Aead, KeyInit, Payload};
use aes_gcm::{Aes256Gcm, Nonce};
use hkdf::Hkdf;
use hmac::{Hmac, Mac};
use rand::RngCore;
use serde::{Deserialize, Serialize};
use sha2::Sha256;

use super::error::IamError;

/// Storage key, in `__system__`, of the key a node generated for itself.
/// Outside `__s4_iam_v2_`: never replicated.
pub const NODE_SECRET_KEY_KEY: &str = "__s4_iam_node_secret_key";

/// HKDF label of the key derived from the JWT secret.
const DERIVATION_LABEL: &[u8] = b"s4-iam-secret-v1";

/// What the id of a key is an HMAC of.
const KEY_ID_LABEL: &[u8] = b"s4-iam-key-id";

/// Bytes of a key.
pub const KEY_LEN: usize = 32;

/// Bytes of a nonce of AES-GCM.
const NONCE_LEN: usize = 12;

/// Where a key comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum KeyOrigin {
    /// `S4_IAM_ENCRYPTION_KEY`.
    Configured,
    /// `S4_IAM_ENCRYPTION_KEY_PREVIOUS`.
    Previous,
    /// Derived from `S4_JWT_SECRET`.
    JwtSecret,
    /// Generated by this node and kept in its own storage.
    Node,
}

/// One key secrets are sealed with.
#[derive(Clone)]
pub struct SecretKey {
    id: String,
    origin: KeyOrigin,
    cipher: Aes256Gcm,
}

impl std::fmt::Debug for SecretKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SecretKey")
            .field("id", &self.id)
            .field("origin", &self.origin)
            .finish_non_exhaustive()
    }
}

impl SecretKey {
    /// The key of `bytes`, from `origin`.
    pub fn new(bytes: &[u8; KEY_LEN], origin: KeyOrigin) -> Self {
        Self {
            id: key_id(bytes),
            origin,
            cipher: Aes256Gcm::new(bytes.into()),
        }
    }

    /// The key of `hex`, 64 hex digits.
    ///
    /// # Errors
    ///
    /// `InvalidSecretKey` when `hex` is not 32 bytes in hex.
    pub fn from_hex(hex: &str, origin: KeyOrigin) -> Result<Self, IamError> {
        let bytes =
            decode_hex(hex.trim()).filter(|bytes| bytes.len() == KEY_LEN).ok_or_else(|| {
                IamError::InvalidSecretKey(
                    "an IAM encryption key is 32 bytes in hex (64 hex digits); generate one with \
                     `openssl rand -hex 32`"
                        .into(),
                )
            })?;
        let mut key = [0u8; KEY_LEN];
        key.copy_from_slice(&bytes);
        Ok(Self::new(&key, origin))
    }

    /// The key derived from `jwt_secret` by HKDF-SHA256.
    pub fn derived_from_jwt_secret(jwt_secret: &str) -> Self {
        let mut key = [0u8; KEY_LEN];
        // The output length is far below HKDF's limit of 255 blocks.
        let _ = Hkdf::<Sha256>::new(None, jwt_secret.as_bytes()).expand(DERIVATION_LABEL, &mut key);
        Self::new(&key, KeyOrigin::JwtSecret)
    }

    /// A random key, generated by this node.
    pub fn generate() -> ([u8; KEY_LEN], Self) {
        let mut key = [0u8; KEY_LEN];
        rand::thread_rng().fill_bytes(&mut key);
        (key, Self::new(&key, KeyOrigin::Node))
    }

    /// The key's id: the first 8 bytes of `HMAC-SHA256(key, "s4-iam-key-id")`,
    /// in hex. Names the key in records, metrics and gossip without telling
    /// anything about it.
    pub fn id(&self) -> &str {
        &self.id
    }

    /// Where the key comes from.
    pub fn origin(&self) -> KeyOrigin {
        self.origin
    }
}

/// The id of key `bytes`.
fn key_id(bytes: &[u8]) -> String {
    // HMAC takes a key of any length.
    let mut mac = match <Hmac<Sha256> as Mac>::new_from_slice(bytes) {
        Ok(mac) => mac,
        Err(_) => return String::new(),
    };
    mac.update(KEY_ID_LABEL);
    encode_hex(&mac.finalize().into_bytes()[..8])
}

/// A secret as a record holds it: sealed with key `key_id`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SealedSecret {
    /// The id of the key it was sealed with.
    pub key_id: String,
    /// The nonce, in hex.
    pub nonce: String,
    /// The ciphertext and its tag, in hex.
    pub data: String,
}

/// The associated data binding a sealed secret to its user and access key.
fn associated_data(user_id: &str, access_key: &str) -> Vec<u8> {
    let mut aad = Vec::with_capacity(user_id.len() + access_key.len() + 16);
    aad.extend_from_slice(b"s4-iam-secret:");
    aad.extend_from_slice(user_id.as_bytes());
    aad.push(0);
    aad.extend_from_slice(access_key.as_bytes());
    aad
}

/// The keys a node seals secrets with and opens them with.
#[derive(Debug, Clone)]
pub struct SecretKeyring {
    current: SecretKey,
    readable: BTreeMap<String, SecretKey>,
}

impl SecretKeyring {
    /// Seals with `current`; opens with it and with `others`.
    pub fn new(current: SecretKey, others: impl IntoIterator<Item = SecretKey>) -> Self {
        let mut readable: BTreeMap<String, SecretKey> =
            others.into_iter().map(|key| (key.id.clone(), key)).collect();
        readable.insert(current.id.clone(), current.clone());
        Self { current, readable }
    }

    /// The key new secrets are sealed with.
    pub fn current(&self) -> &SecretKey {
        &self.current
    }

    /// Every key this node opens secrets with, the current one included.
    pub fn keys(&self) -> impl Iterator<Item = &SecretKey> {
        self.readable.values()
    }

    /// The id of the current key when the pool must share it — configured or
    /// derived from the configured JWT secret — and `None` for a key this
    /// node generated for itself, which no other node has.
    pub fn shared_key_id(&self) -> Option<&str> {
        match self.current.origin {
            KeyOrigin::Node => None,
            _ => Some(&self.current.id),
        }
    }

    /// A 16-byte fingerprint of [`Self::shared_key_id`], for the pool to
    /// compare its nodes' keys by.
    pub fn shared_key_fingerprint(&self) -> Option<[u8; 16]> {
        use sha2::Digest;
        let id = self.shared_key_id()?;
        let digest = Sha256::digest(format!("s4-iam-key:{id}").as_bytes());
        let mut print = [0u8; 16];
        print.copy_from_slice(&digest[..16]);
        Some(print)
    }

    /// Whether this node opens secrets sealed with key `key_id`.
    pub fn opens(&self, key_id: &str) -> bool {
        self.readable.contains_key(key_id)
    }

    /// `secret` sealed with the current key for user `user_id` and its
    /// `access_key`.
    ///
    /// # Errors
    ///
    /// `SecretSealing` if encryption fails.
    pub fn seal(
        &self,
        user_id: &str,
        access_key: &str,
        secret: &str,
    ) -> Result<SealedSecret, IamError> {
        let mut nonce = [0u8; NONCE_LEN];
        rand::thread_rng().fill_bytes(&mut nonce);
        let aad = associated_data(user_id, access_key);
        let data = self
            .current
            .cipher
            .encrypt(
                Nonce::from_slice(&nonce),
                Payload {
                    msg: secret.as_bytes(),
                    aad: &aad,
                },
            )
            .map_err(|_| IamError::SecretSealing("encryption failed".into()))?;
        Ok(SealedSecret {
            key_id: self.current.id.clone(),
            nonce: encode_hex(&nonce),
            data: encode_hex(&data),
        })
    }

    /// The secret `sealed` holds for user `user_id` and its `access_key`.
    ///
    /// # Errors
    ///
    /// `SecretKeyUnknown` when this node has no key of its id;
    /// `SecretSealing` when it does not open: corrupted, or bound to another
    /// user or access key.
    pub fn open(
        &self,
        user_id: &str,
        access_key: &str,
        sealed: &SealedSecret,
    ) -> Result<String, IamError> {
        let key = self
            .readable
            .get(&sealed.key_id)
            .ok_or_else(|| IamError::SecretKeyUnknown(sealed.key_id.clone()))?;
        let nonce = decode_hex(&sealed.nonce)
            .filter(|nonce| nonce.len() == NONCE_LEN)
            .ok_or_else(|| IamError::SecretSealing("malformed nonce".into()))?;
        let data = decode_hex(&sealed.data)
            .ok_or_else(|| IamError::SecretSealing("malformed ciphertext".into()))?;
        let aad = associated_data(user_id, access_key);
        let plain = key
            .cipher
            .decrypt(
                Nonce::from_slice(&nonce),
                Payload {
                    msg: &data,
                    aad: &aad,
                },
            )
            .map_err(|_| IamError::SecretSealing("the secret does not open".into()))?;
        String::from_utf8(plain).map_err(|_| IamError::SecretSealing("not UTF-8 text".into()))
    }
}

/// `HMAC-SHA256(jwt_secret, "jwt-secret-check")`, its first 16 bytes: the
/// pool compares its nodes' JWT secrets by it without learning them (plan
/// CLUSTER-IAM-REPLICATION.md, decision 6).
pub fn jwt_secret_fingerprint(jwt_secret: &str) -> [u8; 16] {
    let mut print = [0u8; 16];
    if let Ok(mut mac) = <Hmac<Sha256> as Mac>::new_from_slice(jwt_secret.as_bytes()) {
        mac.update(b"jwt-secret-check");
        print.copy_from_slice(&mac.finalize().into_bytes()[..16]);
    }
    print
}

/// What a node's configuration says about the keys secrets are sealed with.
#[derive(Clone, Default)]
pub struct SecretKeySettings {
    /// `S4_IAM_ENCRYPTION_KEY`.
    pub key: Option<SecretKey>,
    /// `S4_IAM_ENCRYPTION_KEY_PREVIOUS`.
    pub previous: Option<SecretKey>,
    /// `S4_JWT_SECRET`, when configured; a secret generated at start does not
    /// count, it is gone at the next one.
    pub jwt_secret: Option<String>,
}

impl std::fmt::Debug for SecretKeySettings {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SecretKeySettings")
            .field("key", &self.key)
            .field("previous", &self.previous)
            .field(
                "jwt_secret",
                &self.jwt_secret.as_ref().map(|_| "<redacted>"),
            )
            .finish()
    }
}

impl SecretKeySettings {
    /// The keyring these settings make, with `node_key` — the key this node
    /// generated for itself, if it has one — readable too. `None` when they
    /// name no key and the node has none: the caller generates one.
    pub fn keyring(&self, node_key: Option<SecretKey>) -> Option<Arc<SecretKeyring>> {
        let derived = self.jwt_secret.as_deref().map(SecretKey::derived_from_jwt_secret);
        let current = self.key.clone().or_else(|| derived.clone()).or_else(|| node_key.clone())?;
        let others = [self.previous.clone(), derived, node_key].into_iter().flatten();
        Some(Arc::new(SecretKeyring::new(current, others)))
    }
}

/// `bytes` in lowercase hex.
pub(crate) fn encode_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// The bytes of `hex`; `None` unless it is an even number of hex digits.
pub(crate) fn decode_hex(hex: &str) -> Option<Vec<u8>> {
    if !hex.len().is_multiple_of(2) || !hex.is_ascii() {
        return None;
    }
    (0..hex.len())
        .step_by(2)
        .map(|at| u8::from_str_radix(&hex[at..at + 2], 16).ok())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const HEX_KEY: &str = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f";
    const OTHER_KEY: &str = "1f1e1d1c1b1a191817161514131211100f0e0d0c0b0a09080706050403020100";

    fn ring(hex: &str) -> SecretKeyring {
        SecretKeyring::new(SecretKey::from_hex(hex, KeyOrigin::Configured).unwrap(), [])
    }

    #[test]
    fn a_sealed_secret_opens_for_its_user_and_access_key_only() {
        let keys = ring(HEX_KEY);
        let sealed = keys.seal("u-1", "S4AKONE", "the-secret").unwrap();

        assert_eq!(keys.open("u-1", "S4AKONE", &sealed).unwrap(), "the-secret");
        assert!(!sealed.data.contains("the-secret"));
        assert_eq!(sealed.key_id, keys.current().id());
        assert!(matches!(
            keys.open("u-2", "S4AKONE", &sealed),
            Err(IamError::SecretSealing(_))
        ));
        assert!(matches!(
            keys.open("u-1", "S4AKTWO", &sealed),
            Err(IamError::SecretSealing(_))
        ));
        let mut tampered = sealed.clone();
        tampered.data.replace_range(
            0..2,
            if &sealed.data[0..2] == "00" {
                "01"
            } else {
                "00"
            },
        );
        assert!(matches!(
            keys.open("u-1", "S4AKONE", &tampered),
            Err(IamError::SecretSealing(_))
        ));
    }

    #[test]
    fn every_seal_takes_a_new_nonce() {
        let keys = ring(HEX_KEY);
        let one = keys.seal("u-1", "S4AK", "s").unwrap();
        let two = keys.seal("u-1", "S4AK", "s").unwrap();
        assert_ne!(one.nonce, two.nonce);
        assert_ne!(one.data, two.data);
    }

    #[test]
    fn a_key_it_does_not_have_is_named() {
        let sealed = ring(OTHER_KEY).seal("u-1", "S4AK", "s").unwrap();
        assert!(matches!(
            ring(HEX_KEY).open("u-1", "S4AK", &sealed),
            Err(IamError::SecretKeyUnknown(id)) if id == sealed.key_id
        ));
    }

    #[test]
    fn the_previous_key_opens_and_the_current_one_seals() {
        let old = ring(OTHER_KEY);
        let sealed = old.seal("u-1", "S4AK", "s").unwrap();
        let settings = SecretKeySettings {
            key: Some(SecretKey::from_hex(HEX_KEY, KeyOrigin::Configured).unwrap()),
            previous: Some(SecretKey::from_hex(OTHER_KEY, KeyOrigin::Previous).unwrap()),
            jwt_secret: None,
        };
        let keys = settings.keyring(None).unwrap();
        assert_eq!(keys.open("u-1", "S4AK", &sealed).unwrap(), "s");
        assert_eq!(
            keys.seal("u-1", "S4AK", "s").unwrap().key_id,
            keys.current().id()
        );
        assert_ne!(keys.current().id(), sealed.key_id);
    }

    #[test]
    fn the_key_derived_from_the_jwt_secret_stays_readable_after_a_key_is_configured() {
        let jwt = "a-jwt-secret-of-at-least-32-bytes-long";
        let derived_only = SecretKeySettings {
            jwt_secret: Some(jwt.into()),
            ..Default::default()
        }
        .keyring(None)
        .unwrap();
        assert_eq!(derived_only.current().origin(), KeyOrigin::JwtSecret);
        let sealed = derived_only.seal("u-1", "S4AK", "s").unwrap();

        let configured = SecretKeySettings {
            key: Some(SecretKey::from_hex(HEX_KEY, KeyOrigin::Configured).unwrap()),
            jwt_secret: Some(jwt.into()),
            ..Default::default()
        }
        .keyring(None)
        .unwrap();
        assert_eq!(configured.current().origin(), KeyOrigin::Configured);
        assert_eq!(configured.open("u-1", "S4AK", &sealed).unwrap(), "s");
    }

    #[test]
    fn the_key_derived_from_the_jwt_secret_is_the_same_on_every_node() {
        let jwt = "a-jwt-secret-of-at-least-32-bytes-long";
        assert_eq!(
            SecretKey::derived_from_jwt_secret(jwt).id(),
            SecretKey::derived_from_jwt_secret(jwt).id()
        );
        assert_ne!(
            SecretKey::derived_from_jwt_secret(jwt).id(),
            SecretKey::derived_from_jwt_secret("another-jwt-secret-of-32-bytes-long").id()
        );
    }

    #[test]
    fn without_configured_material_the_node_key_seals_and_is_not_shared() {
        assert!(SecretKeySettings::default().keyring(None).is_none());
        let (_, node) = SecretKey::generate();
        let keys = SecretKeySettings::default().keyring(Some(node.clone())).unwrap();
        assert_eq!(keys.current().id(), node.id());
        assert_eq!(keys.shared_key_id(), None);

        let configured = SecretKeySettings {
            key: Some(SecretKey::from_hex(HEX_KEY, KeyOrigin::Configured).unwrap()),
            ..Default::default()
        }
        .keyring(Some(node.clone()))
        .unwrap();
        assert!(configured.opens(node.id()));
        assert_eq!(configured.shared_key_id(), Some(configured.current().id()));
    }

    #[test]
    fn fingerprints_tell_settings_apart_and_nothing_of_them() {
        let jwt = "a-jwt-secret-of-at-least-32-bytes-long";
        assert_eq!(jwt_secret_fingerprint(jwt), jwt_secret_fingerprint(jwt));
        assert_ne!(
            jwt_secret_fingerprint(jwt),
            jwt_secret_fingerprint("another-jwt-secret-of-32-bytes-long")
        );
        let a = ring(HEX_KEY).shared_key_fingerprint().unwrap();
        assert_eq!(a, ring(HEX_KEY).shared_key_fingerprint().unwrap());
        assert_ne!(a, ring(OTHER_KEY).shared_key_fingerprint().unwrap());
        let (_, node) = SecretKey::generate();
        assert_eq!(SecretKeyring::new(node, []).shared_key_fingerprint(), None);
    }

    #[test]
    fn a_key_must_be_32_bytes_of_hex() {
        assert!(SecretKey::from_hex(HEX_KEY, KeyOrigin::Configured).is_ok());
        assert!(SecretKey::from_hex(&HEX_KEY[..62], KeyOrigin::Configured).is_err());
        assert!(SecretKey::from_hex(&format!("{HEX_KEY}00"), KeyOrigin::Configured).is_err());
        assert!(SecretKey::from_hex(&HEX_KEY.replace('0', "g"), KeyOrigin::Configured).is_err());
        assert!(SecretKey::from_hex(&format!("{HEX_KEY}\n"), KeyOrigin::Configured).is_ok());
    }

    #[test]
    fn the_id_tells_nothing_of_the_key() {
        let key = SecretKey::from_hex(HEX_KEY, KeyOrigin::Configured).unwrap();
        assert_eq!(key.id().len(), 16);
        assert!(!HEX_KEY.contains(key.id()));
        assert!(!format!("{key:?}").contains(HEX_KEY));
    }
}
